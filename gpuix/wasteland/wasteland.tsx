import { existsSync, readFileSync, statSync } from 'fs'
import { render } from '@gpuix/react'
import { App, keyBridge } from './src/ui/App'
import { appendLog, broadcastReader, paths, readSave, sendBroadcast, writeSave } from './src/io'
import { questList } from './src/engine/game'

const HELP = `wasteland - WASTELAND: NEW YORK, a procedural post-apocalyptic RPG for Ghostty/kitty

usage:
  wasteland                 play (title screen; C continues your save)
  wasteland -c, --continue  jump straight into your save
  wasteland -n, --new       skip character creation with default stats
  wasteland log [-f]        print the game log (-f follows it live)
  wasteland save            summarise the save file
  wasteland radio "<text>"  broadcast a message to every running game's WRIST-LINK radio
  wasteland -h, --help      this help

keys: arrows/WASD move  click walk/talk/loot  T target  E end turn  1-5 WRIST-LINK tabs
      Tab toggle panel (narrow)  Z or scroll zoom  ^S save  ^L load  Esc close  ctrl-c quit
files: ${paths.save}, ${paths.log}, ${paths.radio}
zero asset files: every pixel is generated by code at runtime.`

const args = process.argv.slice(2)
const cmd = args[0]

if (cmd === '-h' || cmd === '--help' || cmd === 'help') {
  console.log(HELP)
} else if (cmd === 'log') {
  const show = () => (existsSync(paths.log) ? readFileSync(paths.log, 'utf8') : '')
  const all = show()
  process.stdout.write(all.split('\n').slice(-40).join('\n'))
  if (args.includes('-f')) {
    let off = existsSync(paths.log) ? statSync(paths.log).size : 0
    setInterval(() => {
      if (!existsSync(paths.log)) return
      const size = statSync(paths.log).size
      if (size < off) off = 0
      if (size > off) { process.stdout.write(readFileSync(paths.log).subarray(off, size).toString('utf8')); off = size }
    }, 200)
  }
} else if (cmd === 'radio') {
  const text = args.slice(1).join(' ').trim()
  if (!text) { console.error('usage: wasteland radio "<text>"'); process.exit(1) }
  sendBroadcast(text)
  console.log(`📡 broadcasting on 101.1: "${text}"`)
} else if (cmd === 'save') {
  const s = readSave()
  if (!s) { console.log(`no save at ${paths.save}`); process.exit(0) }
  console.log(`${s.player.name}  LV ${s.player.level}  HP ${s.player.hp}  RAD ${s.player.rads}  caps ${s.player.caps}  turn ${s.turn}  @ (${s.player.x},${s.player.y})`)
  for (const q of questList(s)) console.log(`  ${q.done ? '✓' : '•'} ${q.title}: ${q.text}`)
} else if (cmd && !cmd.startsWith('-')) {
  console.error(`unknown command: ${cmd}\n\n${HELP}`)
  process.exit(1)
} else if (process.env.RUST_LOG !== 'error') {
  const child = Bun.spawn([process.execPath, import.meta.path, ...args], { env: { ...process.env, RUST_LOG: 'error' }, stdio: ['inherit', 'inherit', 'inherit'] })
  process.on('SIGINT', () => {})
  process.exit(await child.exited)
} else {
  const cont = args.includes('-c') || args.includes('--continue')
  // GPUIX prints mount banners via console.log; stdout is held until exit, so they'd land under the restored prompt.
  const rawLog = console.log
  console.log = (...a: unknown[]) => { if (typeof a[0] === 'string' && a[0].startsWith('[gpuix]')) return; rawLog(...a) }
  const initial = cont ? readSave() : null
  render(
    <App
      initial={initial}
      startScreen={cont || args.includes('-n') || args.includes('--new') ? 'game' : 'title'}
      io={{ save: (s) => writeSave(s), load: () => readSave(), log: (l) => appendLog(l), pollBroadcasts: broadcastReader() }}
    />,
    {
      terminal: true,
      onKeyDown: (e, r) => {
        if (performance.now() - keyBridge.handledAt < 50) return
        keyBridge.handle?.current?.(e)
        const id = keyBridge.rootId()
        if (id !== undefined) r.focusElement?.(id)
      },
    },
  )
}
