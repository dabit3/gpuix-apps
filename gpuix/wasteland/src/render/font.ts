export function textWidth(s: string, scale = 1) { return s.length * 6 * scale - scale }
/** Draw text into a lum/hue buffer pair. */
export function drawText(lum: Uint8Array, hue: Uint8Array, w: number, h: number, s: string, x0: number, y0: number, l: number, hu: number, scale = 1) {
  let x = Math.round(x0)
  const y1 = Math.round(y0)
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?']!
    for (let gy = 0; gy < 7; gy++) for (let gx = 0; gx < 5; gx++) {
      if (g[gy * 5 + gx] !== '1') continue
      for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
        const px = x + gx * scale + sx, py = y1 + gy * scale + sy
        if (px < 0 || py < 0 || px >= w || py >= h) continue
        lum[py * w + px] = l; hue[py * w + px] = hu
      }
    }
    x += 6 * scale
  }
}
