// write-mod templates. Each mirrors one reference walkthrough from the original prompt, adapted
// to Grovekeep's official mod API:
//   sword → Terraria + tModLoader: new sword with a custom projectile and generated sprite
//   hud   → Unity Mono + BepInEx: hotkey that toggles a HUD overlay of player stats
//   unit  → Age of Empires II DE: data mod adding a unit variant through the mod folder
import type { SpriteDef } from './assets'

export type TemplateId = 'sword' | 'hud' | 'unit'
export interface Knobs { name: string; color: string; count: number; spread: number; speed: number; pierce: number; trail: number; damage: number; cooldown: number; hudKey: string; enemyHp: number }

export const COLORS: Array<[string, string]> = [['ember', '#ff8a3d'], ['frost', '#39c5cf'], ['gold', '#f0b72f'], ['leaf', '#26cd4d'], ['rose', '#ff6b81'], ['sky', '#71b7ff']]

export const TEMPLATES: Record<TemplateId, { title: string; walkthrough: string; defaults: Knobs }> = {
  sword: { title: 'Weapon + projectile', walkthrough: 'Terraria + tModLoader: sword with custom projectile + sprite', defaults: { name: 'Emberblade', color: '#ff8a3d', count: 5, spread: 12, speed: 170, pierce: 2, trail: 10, damage: 2, cooldown: 0.32, hudKey: 'h', enemyHp: 3 } },
  hud: { title: 'Hotkey HUD overlay', walkthrough: 'Unity Mono + BepInEx: hotkey toggles a stats HUD', defaults: { name: 'Stat Lens', color: '#71b7ff', count: 1, spread: 0, speed: 0, pierce: 0, trail: 0, damage: 0, cooldown: 0, hudKey: 'h', enemyHp: 0 } },
  unit: { title: 'Data mod: enemy variant', walkthrough: 'AoE2 DE: new unit variant via the official mod folder', defaults: { name: 'Frost Slime', color: '#39c5cf', count: 0, spread: 0, speed: 1.4, pierce: 0, trail: 0, damage: 0, cooldown: 0, hudKey: 'h', enemyHp: 4 } },
}

export const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'mod'

export function manifestFor(t: TemplateId, k: Knobs) {
  const hooks = t === 'sword' ? ['init', 'kill', 'swing'] : t === 'hud' ? ['init', 'key', 'tick'] : ['init', 'spawn', 'kill']
  return { id: slug(k.name), name: k.name, version: '1.0.0', entry: 'mod.js', api: 1, description: TEMPLATES[t].walkthrough, hooks }
}

export function modSource(t: TemplateId, k: Knobs, modApiImport: string, sprite?: SpriteDef): string {
  const id = slug(k.name)
  const head = `// ${k.name}: generated by modder from the "${t}" template. Loads through Grovekeep's mod API.\nimport type { ModApi } from '${modApiImport}'\n\n`
  if (t === 'sword') return head + `const SPRITE = ${JSON.stringify(sprite ?? null)}

export default function (api: ModApi) {
  let kills = 0
  let swings = 0
  api.registerWeapon({
    id: '${id}',
    name: '${k.name}',
    damage: ${k.damage},
    cooldown: ${k.cooldown},
    arc: '${k.color}',
    sprite: SPRITE ?? undefined,
    projectile: { speed: ${k.speed}, count: ${k.count}, spread: ${k.spread}, color: '${k.color}', glow: 6, trail: ${k.trail}, pierce: ${k.pierce}, life: 1.1, damage: ${k.damage} },
  })
  const hud = () => api.setHud(['${k.name}', \`\${${k.count}} bolts · pierce ${k.pierce}\`, \`\${swings} swings · \${kills} slain\`])
  api.on('swing', (e) => { if (e.weapon === '${id}') { swings++; hud() } })
  api.on('kill', () => { kills++; hud() })
  api.give('${id}')
  hud()
  api.log('${k.name} equipped: ${k.count} bolts, pierce ${k.pierce}')
}
`
  if (t === 'hud') return head + `export default function (api: ModApi) {
  let on = true
  let acc = 0
  const draw = () => {
    if (!on) return api.setHud([])
    const p = api.game.player
    api.setHud(['${k.name}  [${k.hudKey.toUpperCase()}]', \`hp \${p.hp}/5 · \${api.game.kills} slain\`, \`pos \${Math.round(p.x)},\${Math.round(p.y)} · \${api.game.enemies} foes\`, \`weapon \${p.weapon}\`])
  }
  api.on('key', (e) => { if (e.key === '${k.hudKey}') { on = !on; api.log(on ? 'HUD on' : 'HUD off'); draw() } })
  api.on('tick', (e) => { acc += e.dt; if (acc > 0.2) { acc = 0; draw() } })
  draw()
  api.log('press ${k.hudKey.toUpperCase()} to toggle the stats HUD')
}
`
  return head + `export default function (api: ModApi) {
  api.registerEnemy({
    id: '${id}',
    name: '${k.name}',
    hp: ${k.enemyHp},
    speed: ${k.speed},
    size: 1.5,
    weight: 0.6,
    colors: { body: '${k.color}', shade: '#1f6f8b', light: '#c9f6ff' },
  })
  let slain = 0
  api.on('kill', (e) => { if (e.id === '${id}') { slain++; api.log(\`${k.name} down (\${slain})\`) } })
  api.spawn('${id}', 3)
  api.log('${k.name} joins the spawn table')
}
`
}
